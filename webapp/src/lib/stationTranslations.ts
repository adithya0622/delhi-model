/**
 * Get the translated station name for the given language.
 * Falls back to original name if no translation exists.
 */
export function getTranslatedStationName(name: string, lang: StationLang): string {
  if (lang === "en") return name;

  const map = lang === "hi" ? STATION_NAMES_HI : STATION_NAMES_TA;

  // Exact match
  if (map[name]) return map[name];

  // Try partial match — check if any key is contained in the name
  for (const [key, val] of Object.entries(map)) {
    if (name.includes(key)) {
      return name.replace(key, val);
    }
  }

  return name;
}
